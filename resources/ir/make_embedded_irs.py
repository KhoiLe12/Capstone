#!/usr/bin/env python3
"""
resources/ir/make_embedded_irs.py

Regenerates src/dsp/EmbeddedIRs.h from the body IR WAV files in this folder, so the plugin
needs no external files. Run after replacing any of the WAVs:

    python3 resources/ir/make_embedded_irs.py

Body IRs (see resources/ir/ATTRIBUTION.md for sources and licenses):
    classical_body.wav -> kClassicalBodyWav_*   (BodyResonance::ClassicalIR)
    legacy_body.wav    -> kLegacyBodyWav_*      (BodyResonance::LegacyIR)
    flamenco_body.wav  -> kFlamencoBodyWav_*    (BodyResonance::FlamencoIR)
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'dsp', 'EmbeddedIRs.h')
FILES = [
    ('classical_body.wav', 'kClassicalBodyWav'),
    ('legacy_body.wav', 'kLegacyBodyWav'),
    ('flamenco_body.wav', 'kFlamencoBodyWav'),
]


def main():
    lines = [
        '#pragma once',
        '#include <cstddef>',
        '#include <cstdint>',
        '',
        '// Generated by resources/ir/make_embedded_irs.py - do not edit by hand.',
        '// Sources and licenses: resources/ir/ATTRIBUTION.md',
        '',
    ]
    for fname, symbol in FILES:
        data = open(os.path.join(HERE, fname), 'rb').read()
        lines.append(f'// {fname}')
        lines.append(f'constexpr size_t {symbol}_size = {len(data)};')
        lines.append(f'alignas(16) const uint8_t {symbol}_data[] = {{')
        for i in range(0, len(data), 16):
            lines.append(','.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
        lines.append('};')
        lines.append('')
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines))
    print(f'Wrote {os.path.normpath(OUT)} ({", ".join(f for f, _ in FILES)})')


if __name__ == '__main__':
    main()
